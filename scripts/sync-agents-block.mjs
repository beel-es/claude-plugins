#!/usr/bin/env node
/**
 * Regenerates the AGENTS.md / CLAUDE.md block of the `beel-api:rules` skill.
 *
 * The block is not written by hand: it is the one the documentation publishes
 * on https://docs.beel.es/ai-agents («Give your agent the rules»), built from
 * the fiscal rules marked critical. This script copies it between the markers
 * of `plugins/beel-api/skills/rules/SKILL.md` and touches nothing else.
 *
 * Two sources, same generator:
 *
 *   node scripts/sync-agents-block.mjs
 *       reads the published page, https://docs.beel.es/ai-agents.md
 *
 *   node scripts/sync-agents-block.mjs --docs <path to a docs checkout>
 *       runs the docs' own generator (`agentsSnippet` over the rules
 *       catalogue) in that checkout, for a release that is not deployed yet.
 *       The checkout needs its dependencies installed.
 *
 * `--check` writes nothing and exits 1 when the skill is out of date.
 * `--url <url>` reads another deployment of the docs.
 *
 * No dependencies: Node 20+.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SITE = 'https://docs.beel.es';
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SKILL = join(ROOT, 'plugins', 'beel-api', 'skills', 'rules', 'SKILL.md');
const START = '<!-- agents-block:start — generated by scripts/sync-agents-block.mjs, do not edit -->';
const END = '<!-- agents-block:end -->';

function parseArgs(argv) {
  const args = { check: false, docs: null, url: `${SITE}/ai-agents.md` };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--check') args.check = true;
    else if (a === '--docs') args.docs = argv[++i];
    else if (a === '--url') args.url = argv[++i];
    else {
      console.error(`Unknown argument: ${a}\nUsage: sync-agents-block.mjs [--check] [--docs <dir> | --url <url>]`);
      process.exit(2);
    }
  }
  if (args.docs === undefined || args.url === undefined) {
    console.error('--docs and --url take a value.');
    process.exit(2);
  }
  return args;
}

/** The block as the docs' generator builds it, run inside a docs checkout. */
async function fromCheckout(dir) {
  const docs = resolve(dir);
  const load = (file) => import(pathToFileURL(join(docs, 'lib', file)).href);
  const { loadRules } = await load('rules.mjs');
  const { agentsSnippet } = await load('rules-render.mjs');
  return agentsSnippet(loadRules(docs), SITE);
}

/** The block as published: the ```md fence under «Give your agent the rules». */
async function fromPage(url) {
  const res = await fetch(url, { headers: { Accept: 'text/markdown' } });
  if (!res.ok) throw new Error(`${url} answered ${res.status}`);
  const page = await res.text();
  const section = page.split(/^## Give your agent the rules\s*$/m)[1];
  const block = section?.match(/^```md\n([\s\S]*?)^```$/m)?.[1];
  if (!block) throw new Error(`${url} has no \`\`\`md block under «Give your agent the rules».`);
  return block;
}

const args = parseArgs(process.argv.slice(2));
const block = (args.docs ? await fromCheckout(args.docs) : await fromPage(args.url)).trimEnd();

const current = readFileSync(SKILL, 'utf-8');
const from = current.indexOf(START);
const to = current.indexOf(END);
if (from === -1 || to === -1 || to < from) {
  console.error(`${SKILL}: markers not found.`);
  process.exit(2);
}
const next = `${current.slice(0, from)}${START}\n\n\`\`\`md\n${block}\n\`\`\`\n\n${current.slice(to)}`;

if (args.check) {
  if (next !== current) {
    console.error('The AGENTS.md block of the rules skill is out of date: run node scripts/sync-agents-block.mjs');
    process.exit(1);
  }
  console.log('The AGENTS.md block of the rules skill is up to date.');
} else if (next === current) {
  console.log('No change.');
} else {
  writeFileSync(SKILL, next);
  console.log(`Updated ${SKILL.slice(ROOT.length + 1)}.`);
}
